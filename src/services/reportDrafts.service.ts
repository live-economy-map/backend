import { prisma } from '../config/db.js';
import ApiError from '../utils/ApiError.js';
import { HTTP_STATUS } from '../constants/index.js';
import { generateText } from '../utils/aiClient.js';
import * as emailService from './email.service.js';
import {
  GenerateDraftInput,
  UpdateDraftInput,
  DeliverDraftInput,
} from '../schemas/reportDrafts.schema.js';

export class ReportDraftsService {
  /**
   * Semi-automated AI report draft generation using LLM and cell telemetry.
   */
  async generateDraft(requestId: string, adminId: string, input: GenerateDraftInput) {
    const request = await prisma.reportRequest.findUnique({
      where: { id: requestId },
      include: { user: true },
    });

    if (!request) {
      throw new ApiError(HTTP_STATUS.NOT_FOUND, 'Report request not found');
    }

    const areaCellIds = Array.isArray(request.areaCellIds) ? (request.areaCellIds as string[]) : [];

    // Gather contextual telemetry
    const [snapshots, caseStudies] = await Promise.all([
      prisma.compositeScoreSnapshot.findMany({
        where: { gridCellId: { in: areaCellIds } },
        include: { gridCell: true },
        orderBy: { period: 'desc' },
        take: 10,
      }),
      prisma.caseStudy.findMany({
        where: { isPublished: true },
        take: 3,
        select: { name: true, evidenceDescription: true },
      }),
    ]);

    const cellTelemetryContext = snapshots
      .map(
        (s) =>
          `- Cell ${s.gridCell.areaLabel || s.gridCellId}: Score ${s.compositeScore} on ${
            s.period.toISOString().split('T')[0]
          }`,
      )
      .join('\n');

    const caseStudyContext = caseStudies
      .map((c) => `- Reference Landmark "${c.name}": ${c.evidenceDescription}`)
      .join('\n');

    const prompt = `You are a Senior Spatial Economics Analyst for Live Economy Map.
Generate a structured, professional intelligence report in Markdown format for the following custom research request.

# Request Details
- Title: ${request.title}
- Research Question: ${request.questionPrompt}
- Organization Context: ${request.orgType || 'General'}
- Target Cells Count: ${areaCellIds.length}

# Observed Telemetry & Trends
${cellTelemetryContext || 'No historical telemetry recorded for selected cells.'}

# Ground-Truth Reference Benchmarks
${caseStudyContext || 'No verified benchmarks selected.'}

${input.customPrompt ? `# Additional Analyst Instructions\n${input.customPrompt}\n` : ''}

# Required Sections in Output:
1. Executive Summary
2. Spatial Activity & Signal Dynamics
3. Comparative Benchmarks & Case Study Corroboration
4. Strategic Implications & Economic Outlook

Produce a thorough and factual report in clean Markdown without commentary.`;

    const aiModel = input.model || 'llama-3.3-70b-versatile';
    const draftContent = await generateText(prompt);

    const draft = await prisma.reportDraft.create({
      data: {
        requestId,
        aiModel,
        draftContent,
        status: 'IN_REVIEW',
        reviewerId: adminId,
      },
    });

    // Update parent request to IN_PROGRESS and log event
    await prisma.reportRequest.update({
      where: { id: requestId },
      data: { status: 'IN_PROGRESS' },
    });

    await prisma.reportRequestEvent.create({
      data: {
        requestId,
        actorId: adminId,
        previousStatus: request.status,
        newStatus: 'IN_PROGRESS',
        note: `AI draft generated by analyst (${draft.id})`,
      },
    });

    return draft;
  }

  /**
   * Retrieve report draft by ID with associated request and reviewer metadata.
   */
  async getDraft(draftId: string) {
    const draft = await prisma.reportDraft.findUnique({
      where: { id: draftId },
      include: {
        request: {
          include: {
            user: { select: { id: true, email: true } },
          },
        },
        reviewer: { select: { id: true, email: true } },
      },
    });

    if (!draft) {
      throw new ApiError(HTTP_STATUS.NOT_FOUND, 'Report draft not found');
    }

    return draft;
  }

  /**
   * Reviewer updates draft content, status, or review notes.
   */
  async updateDraft(draftId: string, adminId: string, input: UpdateDraftInput) {
    const existing = await prisma.reportDraft.findUnique({
      where: { id: draftId },
    });

    if (!existing) {
      throw new ApiError(HTTP_STATUS.NOT_FOUND, 'Report draft not found');
    }

    if (existing.status === 'DELIVERED') {
      throw new ApiError(HTTP_STATUS.BAD_REQUEST, 'Delivered drafts cannot be modified');
    }

    return prisma.reportDraft.update({
      where: { id: draftId },
      data: {
        draftContent: input.draftContent,
        reviewNotes: input.reviewNotes,
        status: input.status,
        reviewerId: adminId,
      },
      include: {
        reviewer: { select: { id: true, email: true } },
      },
    });
  }

  /**
   * Explicit approval and delivery step: attaches deliverable, updates parent request, and emails user.
   */
  async deliverDraft(draftId: string, adminId: string, input?: DeliverDraftInput) {
    const draft = await prisma.reportDraft.findUnique({
      where: { id: draftId },
      include: {
        request: {
          include: { user: true },
        },
      },
    });

    if (!draft) {
      throw new ApiError(HTTP_STATUS.NOT_FOUND, 'Report draft not found');
    }

    if (draft.status === 'DELIVERED') {
      throw new ApiError(HTTP_STATUS.BAD_REQUEST, 'Draft is already delivered');
    }

    const deliverable = await prisma.reportDeliverable.create({
      data: {
        requestId: draft.requestId,
        fileUrl: `/reports/deliverables/${draft.id}.md`,
        fileName: `Economic-Report-${draft.requestId.slice(0, 8)}.md`,
        fileSizeBytes: Buffer.byteLength(draft.draftContent, 'utf8'),
        mimeType: 'text/markdown',
        uploadedById: adminId,
      },
    });

    const updatedDraft = await prisma.reportDraft.update({
      where: { id: draft.id },
      data: {
        status: 'DELIVERED',
        reviewNotes: input?.finalNote || draft.reviewNotes,
        reviewerId: adminId,
      },
    });

    await prisma.reportRequest.update({
      where: { id: draft.requestId },
      data: { status: 'DELIVERED' },
    });

    await prisma.reportRequestEvent.create({
      data: {
        requestId: draft.requestId,
        actorId: adminId,
        previousStatus: draft.request.status,
        newStatus: 'DELIVERED',
        note: input?.finalNote || 'AI-assisted draft reviewed, approved, and delivered by analyst',
      },
    });

    await emailService.sendRequestStatusChangeEmail(
      draft.request.user.email,
      draft.request.title,
      'DELIVERED',
      input?.finalNote || 'Your customized economic intelligence report is now ready.',
    );

    return {
      deliverable,
      draft: updatedDraft,
    };
  }
}

export const reportDraftsService = new ReportDraftsService();
